use trail_core::decl::{Base, Declarations, EventDecl, MetricDecl, PropType};

/// Swift's reserved words. A parameter or method with one of these names gets a trailing `_`; an
/// enum case gets backticks.
const KEYWORDS: [&str; 57] = [
    "Any",
    "Protocol",
    "Self",
    "Type",
    "as",
    "associatedtype",
    "await",
    "break",
    "case",
    "catch",
    "class",
    "continue",
    "default",
    "defer",
    "deinit",
    "do",
    "else",
    "enum",
    "extension",
    "fallthrough",
    "false",
    "fileprivate",
    "for",
    "func",
    "guard",
    "if",
    "import",
    "in",
    "init",
    "inout",
    "internal",
    "is",
    "let",
    "nil",
    "open",
    "operator",
    "precedencegroup",
    "private",
    "protocol",
    "public",
    "repeat",
    "rethrows",
    "return",
    "self",
    "static",
    "struct",
    "subscript",
    "super",
    "switch",
    "throw",
    "throws",
    "true",
    "try",
    "typealias",
    "var",
    "where",
    "while",
];

/// Names an event function already uses: its context parameter, its `props` local and the
/// struct's `client`.
const EVENT_SCOPE: [&str; 3] = ["client", "context", "props"];

/// Names a metric function already uses.
const METRIC_SCOPE: [&str; 3] = ["client", "ts", "value"];

fn is_keyword(name: &str) -> bool {
    KEYWORDS.contains(&name)
}

/// The struct names: `agent-logins` → `AgentLoginsEvents`, `AgentLoginsMetrics`.
pub fn struct_name(source: &str, suffix: &str) -> String {
    upper_camel(source) + suffix
}

/// An event or metric's method name: `shop.order.placed` → `shopOrderPlaced`, `class` → `class_`.
pub fn method(name: &str) -> String {
    unreserve(lower_camel(name), &[&KEYWORDS])
}

/// A property's argument label: `order_id` → `orderId`, `class` → `class_`.
pub fn event_param(prop: &str) -> String {
    unreserve(lower_camel(prop), &[&KEYWORDS, &EVENT_SCOPE])
}

/// A label's argument label.
pub fn metric_param(label: &str) -> String {
    unreserve(lower_camel(label), &[&KEYWORDS, &METRIC_SCOPE])
}

/// The nested enum for an enum property: `ShopOrderFailed` + `Reason`.
pub fn enum_type(event: &str, prop: &str) -> String {
    upper_camel(event) + &upper_camel(prop)
}

/// The identifier an enum value's case gets, without backticks: `out-of-stock` → `outOfStock`,
/// `2fa` → `_2fa`. None when the value has no ASCII letter or digit to build one from.
pub fn case_name(value: &str) -> Option<String> {
    let name = lower_camel(value);
    match name.chars().next() {
        None => None,
        Some(first) if first.is_ascii_digit() => Some(format!("_{name}")),
        Some(_) => Some(name),
    }
}

/// The case as written in the declaration: with backticks when it is a keyword.
fn case_decl(value: &str) -> String {
    match case_name(value) {
        Some(name) if is_keyword(&name) => format!("`{name}`"),
        Some(name) => name,
        // `check` refuses this value; write something that fails loudly rather than nothing.
        None => "`<no case name>`".to_string(),
    }
}

fn type_of(event: &str, prop: &str, kind: &PropType) -> String {
    match &kind.base {
        Base::String => "String".to_string(),
        Base::Int => "Int".to_string(),
        Base::Float => "Double".to_string(),
        Base::Bool => "Bool".to_string(),
        Base::StringList => "[String]".to_string(),
        Base::Json => "TrailValue".to_string(),
        Base::Enum(_) => enum_type(event, prop),
    }
}

/// `param` as a `TrailValue`.
fn wrap(param: &str, kind: &PropType) -> String {
    match &kind.base {
        Base::String => format!(".string({param})"),
        Base::Int => format!(".int({param})"),
        Base::Float => format!(".double({param})"),
        Base::Bool => format!(".bool({param})"),
        Base::StringList => format!(".array({param}.map {{ .string($0) }})"),
        Base::Json => param.to_string(),
        Base::Enum(_) => format!(".string({param}.rawValue)"),
    }
}

pub fn generate(decl: &Declarations) -> String {
    let source = &decl.source;
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by `trail gen` from the declarations of `{source}`. Do not edit."
    );
    out.push_str("// Change the TOML files and run `trail gen` again.\n");
    out.push_str("import TrailClient\n\n");

    let _ = writeln!(out, "/// Typed emitters for the events `{source}` declares.");
    push_struct_head(&mut out, &struct_name(source, "Events"));
    for (name, event) in &decl.events {
        push_event(&mut out, name, event);
    }
    out.push_str("}\n\n");

    let _ = writeln!(out, "/// Typed emitters for the metrics `{source}` declares.");
    push_struct_head(&mut out, &struct_name(source, "Metrics"));
    for (name, metric) in &decl.metrics {
        push_metric(&mut out, name, metric);
    }
    out.push_str("}\n");
    out
}

fn push_struct_head(out: &mut String, name: &str) {
    let _ = writeln!(out, "public struct {name}: Sendable {{");
    out.push_str("    private let client: TrailClient\n\n");
    out.push_str("    public init(_ client: TrailClient) {\n");
    out.push_str("        self.client = client\n");
    out.push_str("    }\n");
}

fn push_event(out: &mut String, name: &str, event: &EventDecl) {
    let required: Vec<(&String, &PropType)> = event.props.iter().filter(|(_, p)| !p.optional).collect();
    let optional: Vec<(&String, &PropType)> = event.props.iter().filter(|(_, p)| p.optional).collect();
    let ordered = || required.iter().chain(optional.iter());

    for (prop, kind) in ordered() {
        if let Base::Enum(values) = &kind.base {
            let _ = writeln!(
                out,
                "\n    public enum {}: String, Sendable {{",
                enum_type(name, prop)
            );
            for value in values {
                let _ = writeln!(
                    out,
                    "        case {} = {}",
                    case_decl(value),
                    quote(value, Escape::Swift)
                );
            }
            out.push_str("    }\n");
        }
    }

    let _ = writeln!(out, "\n    /// {}", flatten(&event.description));
    let _ = writeln!(out, "    public func {}(", method(name));
    for (prop, kind) in ordered() {
        let default = if kind.optional { "? = nil" } else { "" };
        let _ = writeln!(
            out,
            "        {}: {}{default},",
            event_param(prop),
            type_of(name, prop, kind)
        );
    }
    out.push_str("        context: EmitContext = EmitContext()\n");
    out.push_str("    ) {\n");
    let binding = if optional.is_empty() { "let" } else { "var" };
    if required.is_empty() {
        let _ = writeln!(out, "        {binding} props: [String: TrailValue] = [:]");
    } else {
        let _ = writeln!(out, "        {binding} props: [String: TrailValue] = [");
        for (prop, kind) in &required {
            let _ = writeln!(
                out,
                "            {}: {},",
                quote(prop, Escape::Swift),
                wrap(&event_param(prop), kind)
            );
        }
        out.push_str("        ]\n");
    }
    for (prop, kind) in &optional {
        let param = event_param(prop);
        let _ = writeln!(
            out,
            "        if let {param} {{ props[{}] = {} }}",
            quote(prop, Escape::Swift),
            wrap(&param, kind)
        );
    }
    let _ = writeln!(
        out,
        "        client.recordEvent({}, props, context)",
        quote(name, Escape::Swift)
    );
    out.push_str("    }\n");
}

fn push_metric(out: &mut String, name: &str, metric: &MetricDecl) {
    let _ = writeln!(
        out,
        "\n    /// {}",
        metric_doc(&metric.description, metric.unit.as_deref())
    );
    let mut params = String::from("_ value: Double, ");
    for label in &metric.labels {
        params.push_str(&format!("{}: String, ", metric_param(label)));
    }
    params.push_str("ts: Int64? = nil");
    let _ = writeln!(out, "    public func {}({params}) {{", method(name));
    let labels = if metric.labels.is_empty() {
        "[:]".to_string()
    } else {
        let pairs: Vec<String> = metric
            .labels
            .iter()
            .map(|label| format!("{}: {}", quote(label, Escape::Swift), metric_param(label)))
            .collect();
        format!("[{}]", pairs.join(", "))
    };
    let unit = match &metric.unit {
        Some(unit) => quote(unit, Escape::Swift),
        None => "nil".to_string(),
    };
    let _ = writeln!(
        out,
        "        client.recordMetric({}, value, labels: {labels}, unit: {unit}, kind: .{}, ts: ts)",
        quote(name, Escape::Swift),
        metric.kind.as_str()
    );
    out.push_str("    }\n");
}
