//! The python generator. Written against spec/client.md.

use crate::names::{Escape, flatten, metric_doc, quote, unreserve};
use std::fmt::Write;
use trail_core::decl::{Base, Declarations, EventDecl, MetricDecl, PropType};

/// Python's keywords. A parameter or method with one of these names gets a trailing `_`.
const KEYWORDS: [&str; 35] = [
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def",
    "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is",
    "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
];

/// Names a method may not take: annotations inside the class body would find the method instead
/// of the type (`def float(...)` then `value: float`).
const CLASS_SCOPE: [&str; 10] = [
    "Any", "Client", "Context", "Literal", "bool", "dict", "float", "int", "list", "str",
];

/// Names an event function already uses: its own parameters and what its body refers to.
const EVENT_SCOPE: [&str; 5] = ["context", "dict", "props", "self", "str"];

/// Names a metric function already uses.
const METRIC_SCOPE: [&str; 3] = ["self", "ts", "value"];

fn snake(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

/// An event or metric's method name: `shop.order.placed` → `shop_order_placed`, `class` →
/// `class_`.
pub fn method(name: &str) -> String {
    unreserve(snake(name), &[&KEYWORDS, &CLASS_SCOPE])
}

/// A property's parameter name: as declared, unless it is a keyword or already taken.
pub fn event_param(prop: &str) -> String {
    unreserve(prop.to_string(), &[&KEYWORDS, &EVENT_SCOPE])
}

/// A label's parameter name.
pub fn metric_param(label: &str) -> String {
    unreserve(label.to_string(), &[&KEYWORDS, &METRIC_SCOPE])
}

fn docstring(text: &str) -> String {
    let mut out = String::new();
    for c in flatten(text).chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            c => out.push(c),
        }
    }
    format!("\"\"\"{out}\"\"\"")
}

fn type_of(prop: &PropType) -> String {
    let base = match &prop.base {
        Base::String => "str".to_string(),
        Base::Int => "int".to_string(),
        Base::Float => "float".to_string(),
        Base::Bool => "bool".to_string(),
        Base::StringList => "list[str]".to_string(),
        Base::Json => "Any".to_string(),
        Base::Enum(values) => {
            let values: Vec<String> = values.iter().map(|v| quote(v, Escape::Python)).collect();
            format!("Literal[{}]", values.join(", "))
        }
    };
    if prop.optional {
        format!("{base} | None = None")
    } else {
        base
    }
}

pub fn generate(decl: &Declarations) -> String {
    let source = &decl.source;
    let has_events = !decl.events.is_empty();
    let has_enum = decl
        .events
        .values()
        .flat_map(|event| event.props.values())
        .any(|prop| matches!(prop.base, Base::Enum(_)));

    let mut out = String::new();
    out.push_str(&format!(
        "# Generated by `trail gen` from the declarations of `{source}`. Do not edit.\n"
    ));
    out.push_str("# Change the TOML files and run `trail gen` again.\n");
    out.push_str("from __future__ import annotations\n\n");
    let typing: Vec<&str> = [("Any", has_events), ("Literal", has_enum)]
        .into_iter()
        .filter_map(|(name, used)| used.then_some(name))
        .collect();
    if !typing.is_empty() {
        out.push_str(&format!("from typing import {}\n\n", typing.join(", ")));
    }
    let imports = if has_events { "Client, Context" } else { "Client" };
    out.push_str(&format!("from trail_client import {imports}\n\n"));
    out.push_str(&format!("SOURCE = {}\n", quote(source, Escape::Python)));

    out.push_str("\n\nclass Events:\n");
    out.push_str(&format!(
        "    \"\"\"Typed emitters for the events `{source}` declares.\"\"\"\n"
    ));
    push_init(&mut out);
    for (name, event) in &decl.events {
        out.push('\n');
        push_event(&mut out, name, event);
    }

    out.push_str("\n\nclass Metrics:\n");
    out.push_str(&format!(
        "    \"\"\"Typed emitters for the metrics `{source}` declares.\"\"\"\n"
    ));
    push_init(&mut out);
    for (name, metric) in &decl.metrics {
        out.push('\n');
        push_metric(&mut out, name, metric);
    }
    out
}

fn push_init(out: &mut String) {
    out.push_str("\n    def __init__(self, client: Client) -> None:\n");
    out.push_str("        self._client = client\n");
}

fn push_event(out: &mut String, name: &str, event: &EventDecl) {
    let required: Vec<(&String, &PropType)> = event.props.iter().filter(|(_, p)| !p.optional).collect();
    let optional: Vec<(&String, &PropType)> = event.props.iter().filter(|(_, p)| p.optional).collect();

    let _ = writeln!(out, "    def {}(", method(name));
    out.push_str("        self,\n        *,\n");
    for (prop, kind) in required.iter().chain(optional.iter()) {
        let _ = writeln!(out, "        {}: {},", event_param(prop), type_of(kind));
    }
    out.push_str("        context: Context | None = None,\n");
    out.push_str("    ) -> None:\n");
    let _ = writeln!(out, "        {}", docstring(&event.description));
    let pairs: Vec<String> = required
        .iter()
        .map(|(prop, _)| format!("{}: {}", quote(prop, Escape::Python), event_param(prop)))
        .collect();
    let _ = writeln!(out, "        props: dict[str, Any] = {{{}}}", pairs.join(", "));
    for (prop, _) in &optional {
        let param = event_param(prop);
        let _ = writeln!(out, "        if {param} is not None:");
        let _ = writeln!(
            out,
            "            props[{}] = {param}",
            quote(prop, Escape::Python)
        );
    }
    let _ = writeln!(
        out,
        "        self._client.record_event({}, props, context)",
        quote(name, Escape::Python)
    );
}

fn push_metric(out: &mut String, name: &str, metric: &MetricDecl) {
    let mut params = String::from("self, value: float, *, ");
    for label in &metric.labels {
        params.push_str(&format!("{}: str, ", metric_param(label)));
    }
    params.push_str("ts: int | None = None");
    let _ = writeln!(out, "    def {}({params}) -> None:", method(name));
    let _ = writeln!(
        out,
        "        {}",
        docstring(&metric_doc(&metric.description, metric.unit.as_deref()))
    );
    let labels: Vec<String> = metric
        .labels
        .iter()
        .map(|label| format!("{}: {}", quote(label, Escape::Python), metric_param(label)))
        .collect();
    let unit = match &metric.unit {
        Some(unit) => quote(unit, Escape::Python),
        None => "None".to_string(),
    };
    let _ = writeln!(
        out,
        "        self._client.record_metric({}, value, {{{}}}, unit={unit}, kind=\"{}\", ts=ts)",
        quote(name, Escape::Python),
        labels.join(", "),
        metric.kind.as_str()
    );
}
