//! The JavaScript generator: the TypeScript output's shape as a plain ES module with JSDoc types,
//! for code that has no build step (a web page that loads its scripts as they are). The types are
//! checked by `tsc --checkJs` or an editor; at run time the file imports nothing.

use crate::names::{Escape, flatten, metric_doc, quote};
use crate::typescript::{method, props_type, type_of};
use std::fmt::Write;
use trail_core::decl::{Base, Declarations, EventDecl, MetricDecl};

/// A description as it appears inside a JSDoc block.
fn text(description: &str) -> String {
    flatten(description).replace("*/", "*\\/").replace('@', "\\@")
}

pub fn generate(decl: &Declarations) -> String {
    let source = &decl.source;
    let has_json = decl
        .events
        .values()
        .flat_map(|event| event.props.values())
        .any(|prop| prop.base == Base::Json);
    let imports: Vec<&str> = [
        ("EmitContext", !decl.events.is_empty()),
        ("JsonValue", has_json),
        ("TrailClient", true),
    ]
    .into_iter()
    .filter_map(|(name, used)| used.then_some(name))
    .collect();

    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by `trail gen` from the declarations of `{source}`. Do not edit."
    );
    out.push_str("// Change the TOML files and run `trail gen` again.\n");
    out.push_str("// @ts-check\n\n");
    let _ = writeln!(
        out,
        "/** @import {{ {} }} from \"trail-client\" */",
        imports.join(", ")
    );
    let _ = writeln!(
        out,
        "\nexport const SOURCE = {};",
        quote(source, Escape::TypeScript)
    );

    for (name, event) in &decl.events {
        out.push('\n');
        push_typedef(&mut out, name, event);
    }

    for (what, function, empty) in [
        ("events", "events", decl.events.is_empty()),
        ("metrics", "metrics", decl.metrics.is_empty()),
    ] {
        out.push_str("\n/**\n");
        let _ = writeln!(out, " * Typed emitters for the {what} `{source}` declares.");
        out.push_str(" * @param {TrailClient} client\n */\n");
        let _ = writeln!(out, "export function {function}(client) {{");
        if empty {
            // Keeps `client` used, so a strict check has nothing to say about an empty half.
            out.push_str("  void client;\n  return {};\n");
        } else {
            out.push_str("  return {\n");
            if what == "events" {
                for (name, event) in &decl.events {
                    push_event(&mut out, name, event);
                }
            } else {
                for (name, metric) in &decl.metrics {
                    push_metric(&mut out, name, metric);
                }
            }
            out.push_str("  };\n");
        }
        out.push_str("}\n");
    }
    out
}

fn push_typedef(out: &mut String, name: &str, event: &EventDecl) {
    out.push_str("/**\n");
    let _ = writeln!(out, " * {}", text(&event.description));
    if event.props.is_empty() {
        let _ = writeln!(out, " * @typedef {{Record<string, never>}} {}", props_type(name));
        out.push_str(" */\n");
        return;
    }
    let _ = writeln!(out, " * @typedef {{object}} {}", props_type(name));
    let required = event.props.iter().filter(|(_, p)| !p.optional);
    let optional = event.props.iter().filter(|(_, p)| p.optional);
    for (prop, kind) in required.chain(optional) {
        let name = if kind.optional {
            format!("[{prop}]")
        } else {
            prop.clone()
        };
        let _ = writeln!(out, " * @property {{{}}} {name}", type_of(kind));
    }
    out.push_str(" */\n");
}

fn push_event(out: &mut String, name: &str, event: &EventDecl) {
    // An event whose properties are all optional can be sent with no argument.
    let all_optional = event.props.values().all(|p| p.optional);
    out.push_str("    /**\n");
    let _ = writeln!(out, "     * {}", text(&event.description));
    let props = if all_optional { "[props]" } else { "props" };
    let _ = writeln!(out, "     * @param {{{}}} {props}", props_type(name));
    out.push_str("     * @param {EmitContext} [context]\n     */\n");
    let default = if all_optional { " = {}" } else { "" };
    let _ = writeln!(out, "    {}(props{default}, context) {{", method(name));
    let _ = writeln!(
        out,
        "      client.recordEvent({}, props, context);",
        quote(name, Escape::TypeScript)
    );
    out.push_str("    },\n");
}

fn push_metric(out: &mut String, name: &str, metric: &MetricDecl) {
    out.push_str("    /**\n");
    let _ = writeln!(
        out,
        "     * {}",
        text(&metric_doc(&metric.description, metric.unit.as_deref()))
    );
    out.push_str("     * @param {number} value\n");
    let (labels_param, labels_arg) = if metric.labels.is_empty() {
        ("", "{}")
    } else {
        let fields: Vec<String> = metric
            .labels
            .iter()
            .map(|label| format!("{label}: string"))
            .collect();
        let _ = writeln!(out, "     * @param {{{{ {} }}}} labels", fields.join(", "));
        (", labels", "labels")
    };
    out.push_str("     * @param {number} [ts]\n     */\n");
    let _ = writeln!(out, "    {}(value{labels_param}, ts) {{", method(name));
    let unit = match &metric.unit {
        Some(unit) => format!("unit: {}, ", quote(unit, Escape::TypeScript)),
        None => String::new(),
    };
    let _ = writeln!(
        out,
        "      client.recordMetric({}, value, {labels_arg}, {{ {unit}kind: \"{}\", ts }});",
        quote(name, Escape::TypeScript),
        metric.kind.as_str()
    );
    out.push_str("    },\n");
}
